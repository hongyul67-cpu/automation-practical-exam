/* 단원 목록 — board.html 이 이 순서로 묶어 보여준다.
   ※ const 로 선언한 값은 window 에 자동으로 붙지 않으므로 아래에서 명시적으로 노출한다. */
const UNITS = (function(){
  const seen=[], out=[];
  LESSON.forEach(function(s,i){
    const u=s.u||'기타';
    let k=seen.indexOf(u);
    if(k<0){ seen.push(u); out.push({name:u, idx:[i]}); }
    else out[k].idx.push(i);
  });
  return out;
})();

/* board.html 에서 window.LESSON / window.UNITS 로 읽는다 */
window.LESSON = LESSON;
window.UNITS  = UNITS;
